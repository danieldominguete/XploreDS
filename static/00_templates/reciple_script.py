from xploreds.log.xds_log import XploreDSLogging

PROJECT_MARKER = "pyproject.toml"


def resolve_project_root(start: Path | None = None) -> Path:
    """
    Locate the XploreDS project root by searching for ``pyproject.toml``.

    Args:
        start: Directory to begin the search. Defaults to this file's folder.

    Returns:
        Absolute path to the project root.

    Raises:
        RuntimeError: When ``pyproject.toml`` cannot be found in any parent folder.
    """
    current = (start or Path(__file__).resolve().parent)

    for path in (current, *current.parents):
        if (path / PROJECT_MARKER).is_file():
            return path

    raise RuntimeError(
        f"Could not find {PROJECT_MARKER} starting from {current}. "
        "Run the script from within the XploreDS repository."
    )


