def main() -> None:
    """Execute the cookbook script pipeline."""
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(line_buffering=True)

    script_path = Path(__file__).resolve()
    project_root = resolve_project_root(script_path.parent)

    load_dotenv(project_root / ".env")

    log = create_logger(project_root, script_path)
    log.init_run()
    log.log_environment_setup()

    try:
        configure_script(log)
        load_datasets(log)
        apply_preprocessing(log)
        apply_business_rules(log)
        save_output_artifacts(log)
    finally:
        log.close_run()


if __name__ == "__main__":
    main()
